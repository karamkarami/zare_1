function rsp_schedule_print(tl)
%RSP_SCHEDULE_PRINT Print the timeline of a scan schedule (run.timeline).
%
%   rsp_schedule_print(run.timeline)

fprintf('\nScan schedule timeline\n');
fprintf(['  #  %-22s %7s %7s %6s %7s %6s %6s %6s %7s %7s %3s %4s %4s %7s %6s %10s\n'], ...
        'name', 'start', 'end', 'turns', 'az0', 'PRF', 'fc', 'Ru', 'vu', 'pulses', ...
        'MTI', 'FFT', 'NCI', 'found', 'false', 'Pfa');
fprintf(['     %-22s %7s %7s %6s %7s %6s %6s %6s %7s %7s %3s %4s %4s %7s %6s %10s\n'], ...
        '', '[s]', '[s]', '', '[deg]', '[Hz]', '[MHz]', '[km]', '[m/s]', '', '', '', '', ...
        '', 'plots', '');
for k = 1:numel(tl.entry)
    fprintf(['  %d  %-22s %7.1f %7.1f %6.2f %7.1f %6g %6g %6.1f %7.1f %7d %3d %4d %4d ' ...
             '%3d/%-3d %6d %10.2e\n'], tl.entry(k), tl.name{k}, tl.startS(k), tl.endS(k), ...
            tl.turns(k), tl.startAzDeg(k), tl.prfHz(k), tl.fcMHz(k), tl.rangeUnambKm(k), ...
            tl.vUnambMps(k), tl.pulses(k), tl.canceler(k), tl.fftPulses(k), tl.nciFrames(k), ...
            tl.found(k), tl.echoes(k), tl.falsePlots(k), tl.pfa(k));
end
fprintf('  (Ru = c/2PRF, vu = +-lambda*PRF/4, MTI = canceler pulses, Pfa = measured per output cell)\n\n');
end
